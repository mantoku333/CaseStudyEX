using System.Collections.Generic;
using Unity.Cinemachine;
using UnityEngine;

/// <summary>
/// One camera area. Pure data plus containment queries: it never decides which room is active
/// and never writes to a camera transform. <see cref="RoomCameraDirector"/> is the only thing
/// that activates a room, which is what keeps camera ownership in a single place.
///
/// Replaces <c>RoomCameraTrigger</c>. The differences that matter:
///   - no static active-room state, no per-frame re-validation, no portal hold
///   - no transform or lens writes, so Cinemachine's own blending stays in charge
///   - no horizontal-follow mode; following is done by the camera's Confiner2D instead
/// </summary>
[AddComponentMenu("Cinemachine/Room Camera Volume")]
[DisallowMultipleComponent]
public sealed class RoomCameraVolume : MonoBehaviour
{
    private static readonly List<RoomCameraVolume> registered = new();

    [Header("Camera")]
    [SerializeField, Tooltip("The camera that frames this room. Required.")]
    private CinemachineCamera roomCamera;

    [SerializeField, Tooltip("Priority while this room is active.")]
    private int activePriority = 20;

    [SerializeField, Tooltip("Priority while this room is inactive.")]
    private int inactivePriority = 0;

    [Header("Area")]
    [SerializeField, Tooltip("Colliders describing the room. Falls back to this object's own Collider2D.")]
    private Collider2D[] areaColliders;

    [Header("Confiner")]
    [SerializeField, Tooltip("Bounding shape handed to this camera's CinemachineConfiner2D. Generated by the migration tool.")]
    private Collider2D confinerBounds;

    private Collider2D[] resolvedColliders;
    private bool hasCachedBounds;
    private Bounds cachedBounds;

    public static IReadOnlyList<RoomCameraVolume> Registered => registered;

    public CinemachineCamera RoomCamera => roomCamera;
    public Collider2D ConfinerBounds => confinerBounds;
    public bool IsUsable => roomCamera != null && ResolveColliders().Length > 0;

    private void Awake()
    {
        if (!registered.Contains(this))
        {
            registered.Add(this);
        }
    }

    private void OnDestroy()
    {
        registered.Remove(this);
    }

    private void OnEnable()
    {
        if (!registered.Contains(this))
        {
            registered.Add(this);
        }

        hasCachedBounds = false;
    }

    private void OnDisable()
    {
        registered.Remove(this);
    }

    private Collider2D[] ResolveColliders()
    {
        if (resolvedColliders != null)
        {
            return resolvedColliders;
        }

        if (areaColliders != null)
        {
            int usable = 0;
            for (int i = 0; i < areaColliders.Length; i++)
            {
                if (areaColliders[i] != null)
                {
                    usable++;
                }
            }

            if (usable > 0)
            {
                Collider2D[] filtered = new Collider2D[usable];
                int next = 0;
                for (int i = 0; i < areaColliders.Length; i++)
                {
                    if (areaColliders[i] != null)
                    {
                        filtered[next++] = areaColliders[i];
                    }
                }

                resolvedColliders = filtered;
                return resolvedColliders;
            }
        }

        resolvedColliders = GetComponents<Collider2D>();
        return resolvedColliders;
    }

    /// <summary>World AABB of the room's area colliders.</summary>
    public Bounds AreaBounds
    {
        get
        {
            if (hasCachedBounds)
            {
                return cachedBounds;
            }

            Collider2D[] colliders = ResolveColliders();
            bool any = false;
            Bounds result = default;
            for (int i = 0; i < colliders.Length; i++)
            {
                Collider2D collider = colliders[i];
                if (collider == null || !collider.enabled)
                {
                    continue;
                }

                if (!any)
                {
                    result = collider.bounds;
                    any = true;
                    continue;
                }

                result.Encapsulate(collider.bounds);
            }

            if (!any)
            {
                result = new Bounds(transform.position, Vector3.zero);
            }

            cachedBounds = result;
            hasCachedBounds = true;
            return cachedBounds;
        }
    }

    /// <summary>Exact containment test against the room's colliders.</summary>
    public bool ContainsPoint(Vector3 worldPosition)
    {
        Collider2D[] colliders = ResolveColliders();
        Vector2 point = new Vector2(worldPosition.x, worldPosition.y);
        for (int i = 0; i < colliders.Length; i++)
        {
            Collider2D collider = colliders[i];
            if (collider != null && collider.enabled && collider.OverlapPoint(point))
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Distance from the point to the nearest room edge. Positive inside, negative outside.
    ///
    /// This is the tie-break when overlapping rooms both contain the player, replacing
    /// "smallest area wins". Area ties were decided by differences under 1% in this project
    /// (Col_212 vs Col_213 differ by one square unit), which made the winner unpredictable
    /// and unrelated to where the player actually came from. Depth is stable and matches
    /// what a player would call "the room I am in".
    /// </summary>
    public float GetDepthInside(Vector3 worldPosition)
    {
        Bounds bounds = AreaBounds;
        float dx = Mathf.Min(worldPosition.x - bounds.min.x, bounds.max.x - worldPosition.x);
        float dy = Mathf.Min(worldPosition.y - bounds.min.y, bounds.max.y - worldPosition.y);
        return Mathf.Min(dx, dy);
    }

    /// <summary>
    /// Largest depth any point in this room can have, i.e. half of its smaller side.
    /// Used to scale the "player must be properly inside before the camera commits"
    /// threshold down for rooms too thin to ever reach a fixed depth.
    /// </summary>
    public float GetMaxDepth()
    {
        Bounds bounds = AreaBounds;
        return Mathf.Min(bounds.extents.x, bounds.extents.y);
    }

    internal void Activate()
    {
        if (roomCamera == null)
        {
            return;
        }

        roomCamera.Priority.Value = activePriority;
        roomCamera.Priority.Enabled = true;
    }

    internal void Deactivate()
    {
        if (roomCamera == null)
        {
            return;
        }

        roomCamera.Priority.Value = inactivePriority;
        roomCamera.Priority.Enabled = true;
    }

#if UNITY_EDITOR
    // Public rather than internal: the migration tool and the tests live in the editor
    // assembly, which cannot see internals of Assembly-CSharp.
    public void EditorAssign(
        CinemachineCamera camera,
        Collider2D[] colliders,
        Collider2D bounds,
        int active,
        int inactive)
    {
        roomCamera = camera;
        areaColliders = colliders;
        confinerBounds = bounds;
        activePriority = active;
        inactivePriority = inactive;
        resolvedColliders = null;
        hasCachedBounds = false;
    }

    private void OnDrawGizmosSelected()
    {
        Bounds bounds = AreaBounds;
        Gizmos.color = new Color(0.25f, 0.9f, 1f, 0.9f);
        Gizmos.DrawWireCube(bounds.center, bounds.size);

        // The confiner shape is a deliberately disabled collider, and Collider2D.bounds
        // reports zero while disabled, so read the box dimensions directly instead.
        if (confinerBounds is BoxCollider2D box)
        {
            Gizmos.color = new Color(1f, 0.75f, 0.2f, 0.9f);
            Gizmos.matrix = box.transform.localToWorldMatrix;
            Gizmos.DrawWireCube(Vector3.zero, new Vector3(box.size.x, box.size.y, 0f));
            Gizmos.matrix = Matrix4x4.identity;
        }
    }
#endif
}
